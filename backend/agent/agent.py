import asyncio
import base64
import json
from google import genai
from google.genai import types
from dotenv import load_dotenv
from pathlib import Path
import os
from fastapi import WebSocket

BASE_DIR = Path(__file__).resolve().parent.parent
load_dotenv(BASE_DIR / ".env")
PARSER_MODEL = os.getenv("PARSER_MODEL", "gemini-3.5-flash-lite")


class InterviewAgent:

    @staticmethod
    async def start_interview(websocket: WebSocket, resume_details: dict):
        """Continuosly takes audio input and pushes to Gemini."""
        llm_google = genai.Client(api_key=os.getenv("GOOGLE_API_KEY"))
        
        full_prompt_text = InterviewAgent.build_interviewer_prompt(resume_details)

        cached_context = llm_google.caches.create(
            model=PARSER_MODEL,
            config=types.CreateCachedContentConfig(
                contents=[types.Content(parts=[types.Part.from_text(text=full_prompt_text)])],
                ttl="120s",
                display_name="interview_session_cache"
            )
        )

        config = types.LiveConnectConfig(
            response_modalities=[types.Modality.AUDIO],
        )

        model_name = os.getenv("GEMINI_MODEL", "gemini-2.0-flash-live-001")
        async with llm_google.aio.live.connect(model=model_name, config=config) as session:
            print("Bidirectional Live Audio-Visual Link established with Gemini using Cached Context.")
            async def upstream_from_flutter():
                """Listens to Flutter's hardware chunks and pipes them to Gemini."""
                try:
                    async for message in websocket.iter_json():
                        # Check what data modality Flutter sent
                        if "audio" in message:
                            raw_audio_bytes = base64.b64decode(message["audio"])
                            await session.send_realtime_input(
                                audio=types.Blob(data=raw_audio_bytes, mime_type="audio/pcm")
                            )
                        elif "video" in message:
                            raw_video_bytes = base64.b64decode(message["video"])
                            await session.send_realtime_input(
                                video=types.Blob(data=raw_video_bytes, mime_type="image/jpeg")
                            )
                except Exception as e:
                    print(f"Upstream disconnect/error: {e}")

            async def downstream_to_flutter():
                """Listens to Gemini's voice thoughts and forwards them back to Flutter."""
                try:
                    async for response in session.receive():
                        server_content = response.server_content
                        if server_content is not None and server_content.model_turn is not None:
                            for part in server_content.model_turn.parts or []:
                                # Catch the live raw audio bytes generated by the model
                                inline_data = part.inline_data
                                if inline_data is not None and inline_data.data is not None:
                                    base64_audio = base64.b64encode(inline_data.data).decode("utf-8")
                                    # Push the packet down to Flutter's playback buffer
                                    await websocket.send_json({"audio": base64_audio})
                except Exception as e:
                    print(f"Downstream disconnect/error: {e}")

            await asyncio.gather(upstream_from_flutter(), downstream_to_flutter())

    @staticmethod
    def build_interviewer_prompt(resume_json: dict) -> str:
        """Formats the resume JSON and constraints into a clean structural context string."""

        formatted_resume = json.dumps(resume_json or {})
        return f"""
        You are an expert HR and technical interviewr. Conduct a professional, coversational audio-visual interview.
        
        CANDIDATE PROFILE(STRUCTURED RESUME DATA):
        {formatted_resume}

        INSTRUCTIONS:
        1. Evaluate candidate answers against this profile and job description.
        2. Dynamically ask hyper-targetted technical questions about their frameworks and projects.
        3. Keep your spoken responses concise and natural for an active audio stream.
        """


        